from sklearn.datasets import make_blobs

X, y = make_blobs(
    n_samples=1000,
    centers=4,
    random_state=42
)

import matplotlib.pyplot as plt

plt.scatter(X[:, 0], X[:, 1], color="gray")
plt.title("Generated Data Before K-Means")
plt.savefig("kmeans_data_before.png")
plt.show()

from sklearn.cluster import KMeans
model = KMeans(n_clusters=4, random_state=42, n_init=10)
labels = model.fit_predict(X)

plt.scatter(X[:, 0], X[:, 1], c=labels, cmap="viridis")

plt.scatter(
    model.cluster_centers_[:, 0],
    model.cluster_centers_[:, 1],
    color="red",
    marker="X",
    s=200,
    label="Cluster Centers"
)

plt.title("Generated Data After K-Means")
plt.legend()
plt.savefig("kmeans_data_after.png")
plt.show()

from skimage import data
coffee = data.coffee()

import matplotlib.pyplot as plt
plt.imshow(coffee)
plt.title("Coffee Image Before K-Means")
plt.axis("off")
plt.savefig("kmeans_image_before.png")
plt.show()

pixels = coffee.reshape(-1, 3)
image_model = KMeans(n_clusters=4, random_state=42, n_init=10)
pixel_labels = image_model.fit_predict(pixels)

new_pixels = image_model.cluster_centers_[pixel_labels]
coffee_after = new_pixels.reshape(coffee.shape).astype("uint8")
plt.imshow(coffee_after)
plt.title("Coffee Image After K-Means")
plt.axis("off")
plt.savefig("kmeans_image_after.png")
plt.show()